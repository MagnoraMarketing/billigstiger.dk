export const PAGE_SIZE = 24;

const imported = fileProducts as unknown as Product[];

function demoActive(): boolean {
  const setting = catalogSourceSetting();
  if (setting === "demo") return true;
  if (setting === "file") return false;
  return imported.length === 0;
}

/**
 * Returns the active catalogue. Products live in data/products.json (git-versioned,
 * generated by scripts/import-products.mjs). The catalogue is small (hundreds of
 * rows), so filtering in memory is simple and fast.
 */
export const getAllProducts = cache(async (): Promise<Product[]> => {
  return demoActive() ? demoProducts : imported;
});

export async function isDemoCatalog(): Promise<boolean> {
  return demoActive();
}

export async function getProductBySlug(slug: string): Promise<Product | undefined> {
  return (await getAllProducts()).find((p) => p.slug === slug);
}

export async function getProductsBySlugs(slugs: string[]): Promise<Product[]> {
  const all = await getAllProducts();
  return slugs.map((s) => all.find((p) => p.slug === s)).filter((p): p is Product => Boolean(p));
}

function normalize(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "");
}

export function matchesQuery(p: Product, q: string): boolean {
  const terms = normalize(q).split(/\s+/).filter(Boolean);
  const hay = normalize([p.name, p.sku, p.brand, p.shortDescription, p.categorySlug, p.specs.material ?? ""].join(" "));
  return terms.every((t) => hay.includes(t));
}

const sorters: Record<SortKey, (a: Product, b: Product) => number> = {
  popular: () => 0,
  "price-asc": (a, b) => a.priceOre - b.priceOre,
  "price-desc": (a, b) => b.priceOre - a.priceOre,
  "height-asc": (a, b) => (a.specs.workingHeight ?? 0) - (b.specs.workingHeight ?? 0),
  "height-desc": (a, b) => (b.specs.workingHeight ?? 0) - (a.specs.workingHeight ?? 0),
  name: (a, b) => a.name.localeCompare(b.name, "da"),
};

export function applyFilters(products: Product[], f: ProductFilters): Product[] {
  const out = products.filter((p) => {
    if (f.category && p.categorySlug !== f.category) return false;
    if (f.q && !matchesQuery(p, f.q)) return false;
    if (f.material?.length && !f.material.includes(p.specs.material as never)) return false;
    if (f.brand?.length && !f.brand.includes(p.brand)) return false;
    const h = p.specs.workingHeight;
    if (f.minHeight != null && (h == null || h < f.minHeight)) return false;
    if (f.maxHeight != null && (h == null || h > f.maxHeight)) return false;
    if (f.minPrice != null && p.priceOre < f.minPrice * 100) return false;
    if (f.maxPrice != null && p.priceOre > f.maxPrice * 100) return false;
    if (f.minLoad != null && (p.specs.maxLoad ?? 0) < f.minLoad) return false;
    if (f.professional && !p.specs.professional) return false;
    if (f.inStock && p.stockStatus !== "in_stock") return false;
    return true;
  });
  return [...out].sort(sorters[f.sort ?? "popular"]);
}

export interface Facets {
  materials: Array<{ value: string; count: number }>;
  brands: Array<{ value: string; count: number }>;
  heightRange: [number, number];
  priceRange: [number, number];
  loads: number[];
}

export function computeFacets(products: Product[]): Facets {
  const count = (vals: string[]) => {
    const m = new Map<string, number>();
    vals.forEach((v) => v && m.set(v, (m.get(v) ?? 0) + 1));
    return [...m.entries()].map(([value, c]) => ({ value, count: c })).sort((a, b) => b.count - a.count);
  };
  const heights = products.map((p) => p.specs.workingHeight).filter((h): h is number => !!h);
  const prices = products.map((p) => p.priceOre / 100);
  return {
    materials: count(products.map((p) => String(p.specs.material ?? ""))),
    brands: count(products.map((p) => p.brand)),
    heightRange: heights.length ? [Math.floor(Math.min(...heights)), Math.ceil(Math.max(...heights))] : [0, 0],
    priceRange: prices.length ? [Math.floor(Math.min(...prices)), Math.ceil(Math.max(...prices))] : [0, 0],
    loads: [...new Set(products.map((p) => p.specs.maxLoad).filter((l): l is number => !!l))].sort((a, b) => a - b),
  };
}

type SP = Record<string, string | string[] | undefined>;

function one(v: string | string[] | undefined): string | undefined {
  return Array.isArray(v) ? v[0] : v;
}
function many(v: string | string[] | undefined): string[] | undefined {
  if (!v) return undefined;
  const arr = (Array.isArray(v) ? v : [v]).flatMap((x) => x.split(",")).filter(Boolean);
  return arr.length ? arr : undefined;
}
function numOrUndef(v: string | string[] | undefined): number | undefined {
  const s = one(v);
  if (s == null || s === "") return undefined;
  const n = Number(s.replace(",", "."));
  return Number.isFinite(n) ? n : undefined;
}

const sortKeys: SortKey[] = ["popular", "price-asc", "price-desc", "height-asc", "height-desc", "name"];

export function parseFilters(sp: SP): ProductFilters {
  const sort = one(sp.sort) as SortKey | undefined;
  return {
    q: one(sp.q)?.slice(0, 100),
    material: many(sp.materiale) as ProductFilters["material"],
    brand: many(sp.maerke),
    minHeight: numOrUndef(sp.hoejdeMin),
    maxHeight: numOrUndef(sp.hoejdeMax),
    minPrice: numOrUndef(sp.prisMin),
    maxPrice: numOrUndef(sp.prisMax),
    minLoad: numOrUndef(sp.belastning),
    professional: one(sp.professionel) === "1",
    inStock: one(sp.lager) === "1",
    sort: sort && sortKeys.includes(sort) ? sort : "popular",
    page: Math.max(1, Math.floor(numOrUndef(sp.side) ?? 1)),
  };
}
